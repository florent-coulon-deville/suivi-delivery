--liquibase formatted sql

-- Les tables du suivi de la delivery : seulement leurs colonnes.
--
-- Format « SQL formaté » de Liquibase : du SQL normal, découpé en changements par des
-- commentaires spéciaux.
--   --changeset auteur:identifiant   début d'un changement (le couple doit être unique) ;
--   --comment ...                    sa description, gardée dans la table databasechangelog ;
--   --rollback ...                   comment l'annuler (commande « liquibase rollback »).
-- Chaque changement est appliqué dans une transaction : entièrement, ou pas du tout.
--
-- Schéma : les tables sont créées dans le schéma de la connexion, « suivi_delivery »
-- (currentSchema dans LIQUIBASE_COMMAND_URL). Ce schéma est créé avec la base (module
-- postgres/, voir docs/postgresql.md) ; « public » reste vide, et Keycloak a son propre schéma.
--
-- Ici, seulement ce qui décrit une colonne : son type, « not null » (obligatoire), « default »
-- (valeur par défaut) et la numérotation automatique de l'identifiant. Les contraintes (clés,
-- unicité, contrôles) et les index sont ajoutés ensuite, avec un nom, par « alter table » :
--   002-primary-keys.sql, 003-unique-and-check-constraints.sql, 004-foreign-keys.sql, 005-index.sql.
--
-- Identifiants : « generated by default as identity » = numérotés par la base (1, 2, 3…),
-- jamais réutilisés après une suppression.
--
-- Les comptes, mots de passe et jetons ne sont pas ici : Keycloak les gère (docs/keycloak.md).


-- ===== Listes gérées dans l'outil ============================================

--changeset suivi-delivery:001-01-environments
--comment: Environnements (int, rec, prod...), avec leur ordre de promotion facultatif.
create table environments (
    id              bigint       generated by default as identity not null,
    code            varchar(30)  not null,
    label           varchar(100) not null,
    is_prod         boolean      not null default false,
    promotion_order integer
);
--rollback drop table environments;

--changeset suivi-delivery:001-02-clusters
--comment: Clusters OpenShift, de prod ou de hors prod.
create table clusters (
    id      bigint       generated by default as identity not null,
    code    varchar(30)  not null,
    label   varchar(100) not null,
    is_prod boolean      not null default false
);
--rollback drop table clusters;

--changeset suivi-delivery:001-03-network-zones
--comment: Zones réseau des namespaces (dmz, interne...).
create table network_zones (
    id    bigint       generated by default as identity not null,
    code  varchar(30)  not null,
    label varchar(100) not null
);
--rollback drop table network_zones;


-- ===== Commande des ressources ===============================================

--changeset suivi-delivery:001-04-applications
--comment: Applications : identifiant unique partout, trigramme partageable.
create table applications (
    id         bigint       generated by default as identity not null,
    identifier varchar(30)  not null,
    name       varchar(100) not null,
    trigram    char(3)      not null
);
--rollback drop table applications;

--changeset suivi-delivery:001-05-namespaces
--comment: Namespaces OpenShift d'une application, par environnement et cluster. Le nom est calculé par l'API.
create table namespaces (
    id              bigint      generated by default as identity not null,
    application_id  bigint      not null,
    environment_id  bigint      not null,
    cluster_id      bigint      not null,
    suffix          varchar(30) not null,
    network_zone_id bigint      not null
);
--rollback drop table namespaces;

--changeset suivi-delivery:001-06-modules
--comment: Modules (programmes) d'une application : CAPABILITY (socle) ou BUSINESS_PROJECT.
create table modules (
    id             bigint       generated by default as identity not null,
    application_id bigint       not null,
    code           varchar(30)  not null,
    name           varchar(100) not null,
    type           varchar(20)  not null
);
--rollback drop table modules;

--changeset suivi-delivery:001-07-dependencies
--comment: Le module A (module_id) a besoin du module B (depends_on_id), y compris entre applications.
create table dependencies (
    id            bigint generated by default as identity not null,
    module_id     bigint not null,
    depends_on_id bigint not null
);
--rollback drop table dependencies;


-- ===== Déploiement ===========================================================

--changeset suivi-delivery:001-08-module-versions
--comment: Versions d'un module : SNAPSHOT (par défaut) ou RELEASE.
create table module_versions (
    id        bigint      generated by default as identity not null,
    module_id bigint      not null,
    number    varchar(50) not null,
    type      varchar(20) not null default 'SNAPSHOT'
);
--rollback drop table module_versions;

--changeset suivi-delivery:001-09-compatibilities
--comment: Versions des modules requis compatibles avec une version de module (bornes comprises).
create table compatibilities (
    id                 bigint      generated by default as identity not null,
    module_version_id  bigint      not null,
    required_module_id bigint      not null,
    condition          varchar(20) not null,
    version            varchar(50) not null,
    version_max        varchar(50)
);
--rollback drop table compatibilities;

--changeset suivi-delivery:001-10-parameters
--comment: Paramètres TECHNICAL ou APPLICATION d'un module : un nom libre (souvent une version).
create table parameters (
    id        bigint      generated by default as identity not null,
    module_id bigint      not null,
    name      varchar(50) not null,
    type      varchar(20) not null
);
--rollback drop table parameters;

--changeset suivi-delivery:001-11-parameter-namespaces
--comment: Namespaces auxquels un paramètre est affecté (plusieurs pour plusieurs) ; position : ordre de la liste.
create table parameter_namespaces (
    parameter_id bigint  not null,
    namespace_id bigint  not null,
    position     integer not null
);
--rollback drop table parameter_namespaces;

--changeset suivi-delivery:001-12-slots
--comment: Emplacements d'un namespace, réservés à un module, nommés par leur release Helm.
create table slots (
    id           bigint      generated by default as identity not null,
    namespace_id bigint      not null,
    module_id    bigint      not null,
    release_name varchar(30) not null
);
--rollback drop table slots;

--changeset suivi-delivery:001-13-installations
--comment: Historique : quelle version, avec quels paramètres, sur quel emplacement, à quelle date.
create table installations (
    id                       bigint      generated by default as identity not null,
    slot_id                  bigint      not null,
    module_version_id        bigint      not null,
    technical_parameter_id   bigint      not null,
    application_parameter_id bigint      not null,
    date                     timestamptz not null
);
--rollback drop table installations;


-- ===== Personnes (connues par Keycloak) =========================================

--changeset suivi-delivery:001-14-preferences
--comment: Préférences de chaque personne (thème de couleurs), repérée par son identifiant Keycloak.
-- subject : l'identifiant Keycloak de la personne (« sub » du jeton), qui ne change jamais.
create table preferences (
    id      bigint      generated by default as identity not null,
    subject varchar(64) not null,
    theme   varchar(20) not null default 'AUTO'
);
--rollback drop table preferences;


-- ===== Journal des actions (backend/app/audit_log.py) ==========================

--changeset suivi-delivery:001-15-audit-log
--comment: Journal : qui a créé, modifié ou supprimé quoi, et quand. Jamais modifié ni effacé.
-- author_id : identifiant Keycloak de l'auteur (« sub ») ; author : son nom de connexion, recopié
-- (le journal reste lisible si le compte est supprimé). object_id : en texte, car les comptes
-- (gérés dans Keycloak) ont des identifiants en lettres et chiffres.
create table audit_log (
    id          bigint       generated by default as identity not null,
    date        timestamptz  not null,
    author_id   varchar(64),
    author      varchar(100) not null,
    author_kind varchar(20)  not null,
    object      varchar(50)  not null,
    object_id   varchar(64)  not null,
    action      varchar(20)  not null,
    before      jsonb,
    after       jsonb
);
--rollback drop table audit_log;
